fn build_app_menu() -> Menu {
    let app = Submenu::with_items(
        "DSH Client",
        true,
        &[
            &PredefinedMenuItem::about(Some("关于 DSH Client"), None),
            &PredefinedMenuItem::separator(),
            &MenuItem::with_id(
                "quit",
                "退出 DSH Client",
                true,
                Some(Accelerator::new(Some(Modifiers::SUPER), Code::KeyQ)),
            ),
        ],
    )
    .unwrap();
    let edit = Submenu::with_items(
        "编辑",
        true,
        &[
            &PredefinedMenuItem::undo(None),
            &PredefinedMenuItem::redo(None),
            &PredefinedMenuItem::separator(),
            &PredefinedMenuItem::cut(None),
            &PredefinedMenuItem::copy(None),
            &PredefinedMenuItem::paste(None),
            &PredefinedMenuItem::select_all(None),
        ],
    )
    .unwrap();
    let view = Submenu::with_items(
        "视图",
        true,
        &[
            &MenuItem::with_id(
                "reload",
                "重新载入界面",
                true,
                Some(Accelerator::new(Some(Modifiers::SUPER), Code::KeyR)),
            ),
            &MenuItem::with_id(
                "devtools",
                "开发者工具",
                true,
                Some(Accelerator::new(
                    Some(Modifiers::SUPER | Modifiers::ALT),
                    Code::KeyI,
                )),
            ),
            &PredefinedMenuItem::separator(),
            &PredefinedMenuItem::minimize(None),
        ],
    )
    .unwrap();
    Menu::with_items(&[&app, &edit, &view]).unwrap()
}

fn build_tray_menu() -> Menu {
    Menu::with_items(&[
        &MenuItem::with_id("toggle", "显示 / 隐藏窗口", true, None),
        &PredefinedMenuItem::separator(),
        &MenuItem::with_id("check-update", "检查更新…", true, None),
        &MenuItem::with_id("restart", "重启 Harness", true, None),
        &MenuItem::with_id("open-config", "打开配置目录 (~/.dsh)", true, None),
        &PredefinedMenuItem::separator(),
        &MenuItem::with_id("quit", "退出 DSH Client", true, None),
    ])
    .unwrap()
}

fn load_tray_icon() -> Icon {
    Icon::from_rgba(TRAY_ICON_RGBA.to_vec(), TRAY_ICON_SIZE, TRAY_ICON_SIZE)
        .expect("invalid tray icon data")
}

