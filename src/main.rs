fn show_loading_page(webview: &Option<WebView>) {
    if let Some(w) = webview {
        let _ = w.load_url(&format!(
            "data:text/html;charset=utf-8,{}",
            percent_encode_all(&loading_html())
        ));
    }
}

fn show_error_page(webview: &Option<WebView>, msg: &str) {
    if let Some(w) = webview {
        let _ = w.load_url(&format!(
            "data:text/html;charset=utf-8,{}",
            percent_encode_all(&error_html(msg))
        ));
    }
}

fn set_status(webview: &Option<WebView>, msg: &str) {
    if let Some(w) = webview {
        let _ = w.evaluate_script(&format!(
            "document.getElementById('status')&&(document.getElementById('status').textContent={});",
            js_string(msg)
        ));
    }
}

/// Escape a string for embedding inside a JavaScript string literal.
fn js_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Percent-encode every byte — always a valid `data:` URL payload.
fn percent_encode_all(s: &str) -> String {
    s.as_bytes()
        .iter()
        .map(|b| format!("%{b:02X}"))
        .collect()
}
